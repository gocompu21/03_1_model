def get_parent(book, code):
    """상위 목차 찾기"""
    if '.' not in code:
        return None
    parent_code = '.'.join(code.split('.')[:-1])
    try:
        return Chapter.objects.get(book=book, code=parent_code)
    except Chapter.DoesNotExist:
        return None

# 목차 입력
created_count = 0
for idx, (code, title) in enumerate(chapters_data):
    level = code.count('.') + 1
    parent = get_parent(book, code)
    
    chapter, created = Chapter.objects.update_or_create(
        book=book,
        code=code,
        defaults={
            'title': title,
            'level': level,
            'parent': parent,
            'order': idx + 1,
        }
    )
    
    if created:
        created_count += 1
        print(f"[생성] {code} {title}")
    else:
        print(f"[업데이트] {code} {title}")

print(f"\n완료! {created_count}개 생성됨")
